import pandas as pd
import matplotlib.pyplot as plt

data = {
    'Name': ['A','B','C','D','E'],
    'Marks': [85,90,None,70,60],
    'Study_Hours': [5,6,4,3,2]
}
df = pd.DataFrame(data)
print(df)

#cleaning
df['Marks']=df['Marks'].fillna(df['Marks'].mean())
print(df)

import numpy as np
df['Grade'] = np.where(df['Marks'] >= 75, 'Pass','Fail')
print(df)

import matplotlib.pyplot as plt


#1.Bar Chart - Employee Salary
plt.figure()
plt.bar(df['Study_Hours'], df['Marks'])
plt.xlabel("Student")
plt.ylabel("Marks")
plt.title("Student Marks- Bar Chart")
plt.show()

#2.Line Chart - Employee Salary
plt.figure()
plt.plot(df["Study_Hours"], df["Marks"], marker = "D")
plt.xlabel("Marks")
plt.ylabel("Student")
plt.title("Student Marks - Line Chart")
plt.show()

#3.Pie Chart - Salary
plt.figure()
plt.pie(
    df['Study_Hours'],
    labels=df["Name"],
    autopct="%1.1f%%"
)
plt.title("Student - Pie Chart")
plt.show()


#4. Histogram - Distribution of Salary
plt.figure()
plt.hist(df["Marks"],bins = 5)
plt.xlabel("Marks")
plt.ylabel("Number of Student")
plt.title("Marks Distribution")
plt.show()

#Visualization
plt.scatter(df['Study_Hours'], df['Marks'])
plt.title("Study Hours vs Marks")
plt.show()
