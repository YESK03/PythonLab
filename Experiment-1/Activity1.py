#Arthimetic operators

a = 15
b = 4

#Addition
print("Addition",a+b)

#Subtraction 
print("Subtraction",a-b)

#Multiplication
print("Multiplication",a*b)

#Division
print("Division",a/b)

#Modulus
print("Modulus",a%b)

#Exponentiation
print("Floor Division",a**b)

#Floor Division
print("Floor Division",a//b)


#Relational Operators

x = 13
y = 33

print(x>y)
print(x<y)
print(x == y)
print(x != y)
print(x >= y)
print(x <= y)



#Logical Operators 

#AND operator
marks_pass = True
attendance_ok = True

result1 = marks_pass and attendance_ok
print(result1)


#NOT operator 
fees_paid = False
result2 = not fees_paid
print(result2)

#OR operator 
o = True 
p = True

result3 = o or p
print(result3)


